// HTTP server logic for the wallet-app plugin. Exposes the
// resolved `ctx.accounts` so a browser-side signer adapter can
// list addresses and request transaction signatures without ever
// loading private keys into JavaScript.
//
// Endpoints (all under `/api/v1/devstack`):
//   GET  /accounts               → { accounts: [{ name, address, scheme, publicKey }] }
//   POST /sign-transaction       → { suiSignature }
//   POST /sign-personal-message  → { signature, bytes }
//
// Auth + reachability defaults are localnet-only:
//   - The listener binds 127.0.0.1, not 0.0.0.0. A coffee-shop LAN
//     attacker who knows the bearer token cannot reach the port.
//   - CORS is restricted to a per-stack allowlist (the manifest's
//     dev-server origin, plus any caller-supplied origins). `*` is
//     never the default.
//   - A 256-bit random bearer token still gates every endpoint; the
//     `?token=...` URL form is supported for the dev-wallet adapter's
//     pairing flow.
//
// These defaults can be overridden via `WalletServerOptions` for
// genuinely-remote dev rigs, but the override is opt-in.
//
// `node:http` and `node:crypto` load via top-level `await import(...)`
// so the static surface stays browser-safe — see `runtime/hash.ts` for
// rationale.

import type { IncomingMessage, Server, ServerResponse } from 'node:http';
import type { Signer } from '@mysten/sui/cryptography';
import { fromBase64, toBase64, isValidSuiAddress } from '@mysten/sui/utils';
import type { AccountsContext } from '../../core/types.js';

const [nodeHttp, nodeCrypto] = await Promise.all([
	import('node:http'),
	import('node:crypto'),
]);

interface WalletServerOptions {
	port: number;
	accounts: AccountsContext;
	/** Token authentication. Generated by the plugin if not supplied;
	 * exposed via the returned handle for logging. */
	token?: string;
	/** Maximum request body size in bytes. Defaults to 2 MB. */
	maxBodyBytes?: number;
	/** Bind address. Defaults to `127.0.0.1` (localhost-only) so a
	 * shared-LAN attacker who somehow learned the bearer token cannot
	 * reach the listener. Override with `'0.0.0.0'` (or a specific NIC)
	 * only for a genuinely-remote dev rig where the user understands
	 * the exposure. */
	host?: string;
	/** Allowed CORS origins. Defaults to `[]` — the server fills in the
	 * dev-server origin from the manifest at registration time. Pass
	 * extra origins for browser tooling that lives off the dev server
	 * (Storybook, a separate test harness). `'*'` is rejected: bearer
	 * tokens leak through manifests baked into the dev bundle, so an
	 * any-origin policy compounds the leak. */
	allowedOrigins?: string[];
}

export interface WalletServerHandle {
	server: Server;
	url: string;
	token: string;
	/** Hot-reload entry point. Replaces the AccountsContext the server
	 * builds its per-request snapshot from, so a supervisor cycle that
	 * resolved a freshly-added account can plumb it into a still-running
	 * listener without restarting (and without reissuing the bearer
	 * token, which apps already cached). The next request rebuilds the
	 * snapshot from the new context. */
	setAccounts: (accounts: AccountsContext) => void;
	/** Hot-reload the CORS allowlist. Used by the supervisor cycle to
	 * fold in `dev-server` once `frontend.dev-server` registers it —
	 * `wallet-app.serve` can start BEFORE vite is up (the only ordering
	 * dep is `register`), so the initial allowlist may be empty and the
	 * frontend's first `/api/v1/devstack/accounts` fetch would 403 with
	 * no `Access-Control-Allow-Origin` header. Re-applying the
	 * sanitization on each call keeps `'*'` rejected. */
	setAllowedOrigins: (allowedOrigins: string[]) => void;
}

interface AccountInfo {
	name: string;
	address: string;
	scheme: string;
	publicKey: string;
}

const DEFAULT_MAX_BODY_BYTES = 2 * 1024 * 1024;

/** Mint a fresh 256-bit bearer token. Exported so the Register action
 * can produce a deterministic token at apply-time (then write it to
 * `<stackDir>/wallet-token` for the listener to pick up). */
export function generateToken(): string {
	return nodeCrypto.randomBytes(32).toString('hex');
}

function buildAccountSnapshot(accounts: AccountsContext): {
	infos: AccountInfo[];
	signersByAddress: Map<string, Signer>;
} {
	const infos: AccountInfo[] = [];
	const signersByAddress = new Map<string, Signer>();
	for (const name of accounts.names()) {
		let signer: Signer;
		try {
			signer = accounts.get(name);
		} catch {
			// Resolver captured an error for this account (e.g. live-net
			// signer misconfigured). Skip — the rest of the API stays usable.
			continue;
		}
		const address = signer.toSuiAddress();
		signersByAddress.set(address, signer);
		infos.push({
			name,
			address,
			scheme: signer.getKeyScheme(),
			publicKey: signer.getPublicKey().toBase64(),
		});
	}
	return { infos, signersByAddress };
}

const DEFAULT_HOST = '127.0.0.1';

export async function startWalletServer(opts: WalletServerOptions): Promise<WalletServerHandle> {
	const token = opts.token ?? generateToken();
	const maxBodyBytes = opts.maxBodyBytes ?? DEFAULT_MAX_BODY_BYTES;
	const host = opts.host ?? DEFAULT_HOST;
	let allowedOrigins = sanitizeAllowedOrigins(opts.allowedOrigins ?? []);
	// Hot-reloadable account source. Each request rebuilds its snapshot
	// from the latest reference so a supervisor cycle that swaps the
	// accounts context (account added to `devstack.config.ts` between
	// cycles) is reflected on the next /accounts list or /sign request
	// without restarting the listener.
	let activeAccounts = opts.accounts;
	let cachedSnapshot = buildAccountSnapshot(activeAccounts);
	let cachedFor = activeAccounts;
	const currentSnapshot = (): typeof cachedSnapshot => {
		if (cachedFor !== activeAccounts) {
			cachedSnapshot = buildAccountSnapshot(activeAccounts);
			cachedFor = activeAccounts;
		}
		return cachedSnapshot;
	};

	const server = nodeHttp.createServer(async (req, res) => {
		const origin = typeof req.headers.origin === 'string' ? req.headers.origin : undefined;
		applyCorsHeaders(res, origin, allowedOrigins);
		if (req.method === 'OPTIONS') {
			// Reject preflight from a non-allowlisted origin so the browser
			// surfaces a CORS error instead of a misleading 200. Same-origin
			// requests don't carry an `Origin` header, so undefined passes.
			if (origin !== undefined && !originAllowed(origin, allowedOrigins)) {
				res.statusCode = 403;
				res.end();
				return;
			}
			res.statusCode = 204;
			res.end();
			return;
		}
		try {
			const url = new URL(req.url ?? '/', `http://${host}:${opts.port}`);
			if (req.method === 'GET' && url.pathname === '/health') {
				return sendJson(res, 200, { ok: true });
			}
			// Block any request whose Origin header doesn't match the
			// allowlist (CORS pre-checks live in the browser; this is a
			// belt-and-suspenders server-side guard against a same-machine
			// attacker who's bypassed the OPTIONS preflight).
			if (origin !== undefined && !originAllowed(origin, allowedOrigins)) {
				return sendJson(res, 403, { error: `Origin ${origin} not allowed` });
			}
			if (!isAuthorized(req, token)) {
				return sendJson(res, 401, {
					error: 'Authentication required. Pair via the URL printed at startup.',
				});
			}
			if (req.method === 'GET' && url.pathname === '/api/v1/devstack/accounts') {
				return sendJson(res, 200, { accounts: currentSnapshot().infos });
			}
			if (req.method === 'POST' && url.pathname === '/api/v1/devstack/sign-transaction') {
				return await handleSign(req, res, currentSnapshot().signersByAddress, maxBodyBytes);
			}
			if (req.method === 'POST' && url.pathname === '/api/v1/devstack/sign-personal-message') {
				return await handleSignPersonalMessage(
					req,
					res,
					currentSnapshot().signersByAddress,
					maxBodyBytes,
				);
			}
			sendJson(res, 404, { error: `No route for ${req.method} ${url.pathname}` });
		} catch (err) {
			const message = err instanceof Error ? err.message : String(err);
			sendJson(res, 500, { error: `Internal error: ${message}` });
		}
	});

	// Await the 'listening' event so the returned handle's
	// `server.address()` is immediately readable. Tests that pass
	// `port: 0` rely on this to discover the assigned port; the
	// production wallet-app flow doesn't care but the cost is one
	// microtask.
	await new Promise<void>((resolve, reject) => {
		const onError = (err: Error) => {
			server.off('listening', onListening);
			reject(err);
		};
		const onListening = () => {
			server.off('error', onError);
			resolve();
		};
		server.once('error', onError);
		server.once('listening', onListening);
		server.listen(opts.port, host);
	});
	const addr = server.address();
	const resolvedPort =
		typeof addr === 'object' && addr !== null && 'port' in addr ? addr.port : opts.port;
	const url = `http://${displayHost(host)}:${resolvedPort}`;
	return {
		server,
		url,
		token,
		setAccounts: (accounts) => {
			activeAccounts = accounts;
			// `cachedFor` mismatch on next request triggers a rebuild.
		},
		setAllowedOrigins: (next) => {
			allowedOrigins = sanitizeAllowedOrigins(next);
		},
	};
}

/** Reject `'*'` with a clear error; otherwise normalize each entry to
 * its `URL.origin` form so trailing slashes / paths don't subtly break
 * matching. */
function sanitizeAllowedOrigins(input: string[]): string[] {
	const out: string[] = [];
	for (const raw of input) {
		if (raw === '*') {
			throw new Error(
				'wallet-app: allowedOrigins cannot include "*" — bearer tokens leak through ' +
					'manifests baked into the dev bundle, so any-origin policies compound the leak. ' +
					'Pass the dev-server origin (e.g. "http://localhost:5173") explicitly.',
			);
		}
		try {
			out.push(new URL(raw).origin);
		} catch {
			throw new Error(`wallet-app: invalid origin in allowedOrigins: ${raw}`);
		}
	}
	return out;
}

function originAllowed(origin: string, allowed: string[]): boolean {
	if (allowed.length === 0) return false;
	return allowed.includes(origin);
}

function applyCorsHeaders(res: ServerResponse, origin: string | undefined, allowed: string[]): void {
	res.setHeader('Vary', 'Origin');
	if (origin !== undefined && originAllowed(origin, allowed)) {
		res.setHeader('Access-Control-Allow-Origin', origin);
	}
	res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
	res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');
	res.setHeader('Access-Control-Max-Age', '86400');
}

function displayHost(host: string): string {
	if (host === '0.0.0.0' || host === '::') return 'localhost';
	return host;
}

function isAuthorized(req: IncomingMessage, token: string): boolean {
	const header = req.headers.authorization;
	if (typeof header !== 'string' || !/^bearer /i.test(header)) {
		const url = new URL(req.url ?? '/', `http://localhost`);
		const queryToken = url.searchParams.get('token');
		if (queryToken === null) return false;
		return safeEqualHex(queryToken, token);
	}
	const provided = header.slice(7);
	return safeEqualHex(provided, token);
}

function safeEqualHex(provided: string, expected: string): boolean {
	if (provided.length !== expected.length) return false;
	return nodeCrypto.timingSafeEqual(Buffer.from(provided), Buffer.from(expected));
}

async function readJsonBody(
	req: IncomingMessage,
	maxBodyBytes: number,
): Promise<Record<string, unknown>> {
	const chunks: Buffer[] = [];
	let total = 0;
	for await (const chunk of req) {
		const buf = chunk instanceof Buffer ? chunk : Buffer.from(chunk);
		total += buf.length;
		if (total > maxBodyBytes) {
			throw new RequestError(413, 'Request body too large');
		}
		chunks.push(buf);
	}
	const raw = Buffer.concat(chunks).toString('utf8');
	if (raw.length === 0) return {};
	try {
		const parsed = JSON.parse(raw) as unknown;
		if (parsed === null || typeof parsed !== 'object') {
			throw new RequestError(400, 'Body must be a JSON object');
		}
		return parsed as Record<string, unknown>;
	} catch (err) {
		if (err instanceof RequestError) throw err;
		throw new RequestError(400, 'Invalid JSON body');
	}
}

async function handleSign(
	req: IncomingMessage,
	res: ServerResponse,
	signers: Map<string, Signer>,
	maxBodyBytes: number,
): Promise<void> {
	let body: Record<string, unknown>;
	try {
		body = await readJsonBody(req, maxBodyBytes);
	} catch (err) {
		if (err instanceof RequestError) return sendJson(res, err.status, { error: err.message });
		throw err;
	}
	const address = body['address'];
	const txBytes = body['txBytes'];
	if (typeof address !== 'string' || !isValidSuiAddress(address)) {
		return sendJson(res, 400, { error: 'Invalid address; expected 0x-prefixed hex' });
	}
	if (typeof txBytes !== 'string' || txBytes.length === 0) {
		return sendJson(res, 400, { error: 'Invalid txBytes; expected non-empty base64 string' });
	}
	const signer = signers.get(address);
	if (signer === undefined) {
		return sendJson(res, 404, { error: `No signer for address ${address}` });
	}
	let bytes: Uint8Array;
	try {
		bytes = fromBase64(txBytes);
	} catch {
		return sendJson(res, 400, { error: 'txBytes is not valid base64' });
	}
	const { signature } = await signer.signTransaction(bytes);
	sendJson(res, 200, { suiSignature: signature, txBytes: toBase64(bytes) });
}

async function handleSignPersonalMessage(
	req: IncomingMessage,
	res: ServerResponse,
	signers: Map<string, Signer>,
	maxBodyBytes: number,
): Promise<void> {
	let body: Record<string, unknown>;
	try {
		body = await readJsonBody(req, maxBodyBytes);
	} catch (err) {
		if (err instanceof RequestError) return sendJson(res, err.status, { error: err.message });
		throw err;
	}
	const address = body['address'];
	const messageBytes = body['messageBytes'];
	if (typeof address !== 'string' || !isValidSuiAddress(address)) {
		return sendJson(res, 400, { error: 'Invalid address; expected 0x-prefixed hex' });
	}
	if (typeof messageBytes !== 'string' || messageBytes.length === 0) {
		return sendJson(res, 400, {
			error: 'Invalid messageBytes; expected non-empty base64 string',
		});
	}
	const signer = signers.get(address);
	if (signer === undefined) {
		return sendJson(res, 404, { error: `No signer for address ${address}` });
	}
	let bytes: Uint8Array;
	try {
		bytes = fromBase64(messageBytes);
	} catch {
		return sendJson(res, 400, { error: 'messageBytes is not valid base64' });
	}
	const { signature } = await signer.signPersonalMessage(bytes);
	sendJson(res, 200, { signature, bytes: toBase64(bytes) });
}

function sendJson(res: ServerResponse, status: number, body: unknown): void {
	res.statusCode = status;
	res.setHeader('Content-Type', 'application/json; charset=utf-8');
	res.end(JSON.stringify(body));
}

class RequestError extends Error {
	constructor(
		readonly status: number,
		message: string,
	) {
		super(message);
	}
}
